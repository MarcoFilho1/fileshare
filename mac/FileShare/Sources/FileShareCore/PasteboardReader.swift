import AppKit
import UniformTypeIdentifiers

/// Decide o que uma cópia no Mac vira para o tablet.
public enum PasteboardReader {
    /// Marca o que o próprio FileShare escreveu, para não devolver ao tablet (eco).
    public static let originType = NSPasteboard.PasteboardType("dev.marcofilho.fileshare.origin")

    /// Convenção de nspasteboard.org usada por gerenciadores de senha e afins.
    static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    public static func read(_ pasteboard: NSPasteboard) -> ClipPayload? {
        let types = Set(pasteboard.types ?? [])
        if types.contains(originType) || !types.isDisjoint(with: privateTypes) { return nil }

        // Print (⌘⇧⌃4 / destino "área de transferência") e a maioria dos apps já entregam PNG.
        if let png = pasteboard.data(forType: .png) {
            return ClipPayload(mime: "image/png", data: png)
        }
        // Arquivo copiado no Finder: só imagens; outros arquivos ainda não são suportados.
        // Precisa vir antes do TIFF, que no Finder é o ícone do arquivo.
        if types.contains(.fileURL) {
            let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
            guard let url = urls?.first, isImageFile(url),
                  let data = try? Data(contentsOf: url), let png = ImageConversion.png(from: data),
                  png.count <= Wire.maxPayload
            else { return nil }
            return ClipPayload(mime: "image/png", data: png)
        }
        if let tiff = pasteboard.data(forType: .tiff), let png = ImageConversion.png(from: tiff) {
            return ClipPayload(mime: "image/png", data: png)
        }
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return ClipPayload(mime: "text/plain", data: Data(text.utf8))
        }
        return nil
    }

    static func isImageFile(_ url: URL) -> Bool {
        guard let type = UTType(filenameExtension: url.pathExtension) else { return false }
        return type.conforms(to: .image)
    }
}
